"""
Панель демонстрации, генерации тестовых данных и диагностики системы.
Идеально подходит для быстрой демонстрации работы платформы преподавателю или комиссии.
"""
import streamlit as st
try:
    from app.api_client import APIClient
except ImportError:
    try:
        from ..api_client import APIClient
    except ImportError:
        from api_client import APIClient


def render_demo_view(client: APIClient):
    st.header("🧪 Демо-панель и генератор тестовых данных")
    st.caption("Инструменты для быстрой проверки всего жизненного цикла отклика")

    # ── Блок 1: Диагностика связи ─────────────────────────────────────────────
    st.subheader("📡 Статус подключения к бэкенду")
    is_alive, msg = client.check_health()
    if is_alive:
        st.success(f"🟢 **API Gateway:** {msg} ({client.base_url})")
    else:
        st.error(f"🔴 **API Gateway:** {msg}")
        st.info("Убедитесь, что сервисы запущены через `docker-compose up -d` или локально на порту 8000.")

    st.divider()

    # ── Блок 2: Генерация тестового кандидата ──────────────────────────────────
    st.subheader("⚡ Генератор тестового скрининга в 1 клик")
    st.write(
        "Нажмите кнопку ниже, чтобы автоматически создать в базе данных:\n"
        "- Тестовый проект (*Финтех Платформа*)\n"
        "- Должность (*Junior/Middle Python Developer*)\n"
        "- Пул вопросов и эталонных ответов\n"
        "- Кандидата (*Алексей Смирнов*)\n"
        "- Отклик со статусом *«Ожидание скрининга»* и сгенерированным токеном"
    )

    if st.button("🚀 Создать тестового кандидата и получить токен", type="primary", use_container_width=True):
        with st.spinner("Создание сущностей в базе данных..."):
            demo_data, err = client.seed_demo_data()
            if err:
                st.error(f"Не удалось сгенерировать демо-данные: {err}")
            else:
                st.success("🎉 Тестовый кандидат успешно создан в базе данных!")
                token = demo_data.get("token")
                resp_id = demo_data.get("response_id")
                cand_name = demo_data.get("full_name")

                st.session_state["last_demo_token"] = token

                st.markdown(
                    f"""
                    * **ФИО:** `{cand_name}`
                    * **ID отклика:** `{resp_id}`
                    * **Сгенерированный токен:** `{token}`
                    """
                )

                st.code(token, language="text")

                if st.button("➡️ Перейти к прохождению интервью от лица кандидата", type="secondary"):
                    st.session_state["candidate_token"] = token
                    st.session_state["nav_role"] = "👤 Кандидат"
                    st.rerun()

    st.divider()

    # ── Блок 3: Инструкция по защите проекта ──────────────────────────────────
    st.subheader("📖 Сценарий демонстрации (Шпаргалка для защиты)")
    with st.expander("Как показать полный цикл работы системы (5 шагов):", expanded=True):
        st.markdown(
            """
            1. **Создание отклика:** В этой вкладке нажать *«Создать тестового кандидата»*, скопировать сгенерированный токен.
            2. **Интервью (Контур Кандидата):** Переключиться на роль **«👤 Кандидат»**, вставить токен, прослушать приветствие, подтвердить согласие на ПДн (152-ФЗ), ответить на 3 вопроса голосом или файлом и нажать *«Завершить скрининг»*.
            3. **ИИ-оценка (Бэкенд):** Модель LLM сравнивает ответы кандидата с эталонами пула вопросов и выставляет первичный балл `ai_score`.
            4. **Слепая оценка (Контур HR):** Переключиться на роль **«🧑‍💼 HR-специалист»**, открыть кандидата, прочитать расшифровку, выставить независимый балл `hr_score` и комментарий. Система сгенерирует Word-отчёт (`.docx`).
            5. **Решение (Контур ЛПР):** Переключиться на роль **«👔 ЛПР»**, увидеть обе оценки рядом, скачать сформированный `.docx` отчёт и нажать *«Пригласить на второй этап»*.
            """
        )
